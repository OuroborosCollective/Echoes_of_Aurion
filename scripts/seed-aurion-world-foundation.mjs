#!/usr/bin/env node
/**
 * Seeds the Aurion world-entity foundation tables (definitions only) with the
 * REAL canonical content from `shared/aurionAx1ContentCatalog.json` — no
 * placeholder data. Emits idempotent INSERT ... ON DUPLICATE KEY UPDATE SQL to
 * `drizzle/seed_0064_aurion_world_foundation.sql`.
 *
 * Re-run after the catalog changes to re-sync definitions; the per-row
 * `contentHash` (sha256 of the definition JSON) lets a drifted seed be detected.
 *
 *   node scripts/seed-aurion-world-foundation.mjs
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const catalog = JSON.parse(readFileSync(resolve(root, "shared/aurionAx1ContentCatalog.json"), "utf8"));

const sourceCatalog = "aurion-ax1-content";
const contentVersion = catalog.contentVersion;

const esc = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
const json = (v) => esc(JSON.stringify(v));
const hash = (v) => createHash("sha256").update(JSON.stringify(v)).digest("hex");

const vals = (rows) => rows.map((r) => `(${r.join(", ")})`).join(",\n  ");

const professions = catalog.professions.map((p) => [
  esc(p.id), esc(p.sourceId), esc(p.category), esc(p.label),
  esc(p.mastery.join(":")), p.unbounded === false ? "false" : "true",
  json(p), esc(sourceCatalog), esc(contentVersion), hash(p), "1",
]);

const activities = catalog.activities.map((a) => [
  esc(a.id), esc(a.professionId), esc(a.kind),
  esc(a.output[0]), esc(a.output[1]),
  json(a), esc(sourceCatalog), esc(contentVersion), hash(a), "1",
]);

const recipes = catalog.recipes.map((r) => [
  esc(r.id), esc(r.professionId), esc(r.label),
  esc(r.output[0]),
  json(r), esc(sourceCatalog), esc(contentVersion), hash(r), "1",
]);

const worldBosses = catalog.worldBosses.map((b) => [
  esc(b.id), esc(b.label), esc(b.zone), esc(b.respawnTicksExact),
  json(b), esc(sourceCatalog), esc(contentVersion), hash(b), "1",
]);

const out = [];
out.push(`-- Aurion world-entity foundation seed. Definitions only; sourced from ${contentVersion}.`);
out.push(`-- Generated by scripts/seed-aurion-world-foundation.mjs. Re-run to re-sync.`);
out.push("");

const blocks = [
  {
    table: "aurionProfessionDefinitions",
    cols: "`id`,`sourceId`,`category`,`displayName`,`masteryScope`,`unbounded`,`definitionJson`,`sourceCatalog`,`contentVersion`,`contentHash`,`definitionVersion`",
    rows: professions,
  },
  {
    table: "aurionActivityDefinitions",
    cols: "`id`,`professionId`,`kind`,`outputItemKey`,`outputItemLabel`,`definitionJson`,`sourceCatalog`,`contentVersion`,`contentHash`,`definitionVersion`",
    rows: activities,
  },
  {
    table: "aurionRecipeDefinitions",
    cols: "`id`,`professionId`,`displayName`,`outputItemKey`,`definitionJson`,`sourceCatalog`,`contentVersion`,`contentHash`,`definitionVersion`",
    rows: recipes,
  },
  {
    table: "aurionWorldBossDefinitions",
    cols: "`id`,`displayName`,`zoneKey`,`respawnTicksExact`,`definitionJson`,`sourceCatalog`,`contentVersion`,`contentHash`,`definitionVersion`",
    rows: worldBosses,
  },
];

for (const block of blocks) {
  if (block.rows.length === 0) continue;
  out.push(`INSERT INTO \`${block.table}\` (${block.cols}) VALUES`);
  out.push("  " + vals(block.rows));
  out.push("ON DUPLICATE KEY UPDATE `contentHash`=VALUES(`contentHash`), `definitionJson`=VALUES(`definitionJson`), `contentVersion`=VALUES(`contentVersion`), `definitionVersion`=VALUES(`definitionVersion`), `updatedAt`=CURRENT_TIMESTAMP;");
  out.push("");
}

const target = resolve(root, "drizzle/seed_0064_aurion_world_foundation.sql");
writeFileSync(target, out.join("\n") + "\n", "utf8");
console.log(`Wrote ${target} (${professions.length} professions, ${activities.length} activities, ${recipes.length} recipes, ${worldBosses.length} world bosses).`);
